/* woff2_smoketest.cpp — smoke test de la cascade brotli(dec) + woff2(dec), MIT.
 *
 * But : valider que le decompresseur de polices WOFF2 vendore (google/woff2,
 * decodeur-seul) et sa dependance brotli (decodeur-seul) compilent, linkent et
 * RECONSTRUISENT reellement un sfnt (TTF/OTF) a partir d'un WOFF2, sur la
 * toolchain OWL, AVANT que le branchement OWL (chargement de polices web dans
 * src/ui_qt.cpp) les consomme. Lot feature separe ; ici, aucune glue OWL.
 *
 * C++ (et non .c) car l'API publique woff2::ConvertWOFF2ToTTF vit dans un
 * namespace C++ (woff2/decode.h) — impossible a appeler depuis du C pur. Le
 * consommateur reel (ui_qt.cpp) est lui aussi C++, compile par la meme
 * toolchain d'arbre principal que owl_woff2 -> ABI std:: coherente (c'est la
 * raison de compiler owl_woff2 EN ARBRE, pas via un sous-build zig/libc++).
 *
 * Fixture embarquee : un WOFF2 minimal (292 octets) d'une police TTF jouet
 * (1 glyphe), genere hors-ligne. Le test prouve au RUNTIME :
 *   1. ComputeWOFF2FinalSize rend une taille sfnt plausible (> entete sfnt).
 *   2. ConvertWOFF2ToTTF decompresse (brotli) + reconstruit la table dir sfnt,
 *      et le resultat porte un magic sfnt valide : 0x00010000 (TrueType) ou
 *      'OTTO' (CFF). C'est la preuve que brotli ET la reconstruction woff2
 *      tournent de bout en bout, pas juste que ca linke.
 *
 * Verifs : exit 0 si tout passe, != 0 + message sinon.
 */

