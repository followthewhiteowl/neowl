static int fail(const char* msg) {
    std::fprintf(stderr, "woff2_smoketest ECHEC : %s\n", msg);
    return 1;
}

int main() {
    const uint8_t* in = kWoff2Min;
    const size_t in_len = sizeof(kWoff2Min);

    size_t final_size = woff2::ComputeWOFF2FinalSize(in, in_len);
    if (final_size < 12)  /* entete sfnt = 12 octets minimum */
        return fail("ComputeWOFF2FinalSize : taille sfnt implausible");

    std::vector<uint8_t> out(final_size);
    if (!woff2::ConvertWOFF2ToTTF(out.data(), out.size(), in, in_len))
        return fail("ConvertWOFF2ToTTF a echoue (brotli ou reconstruction sfnt)");

    if (out.size() < 4) return fail("sfnt reconstruit trop court");
    uint32_t magic = (uint32_t)out[0] << 24 | (uint32_t)out[1] << 16 |
                     (uint32_t)out[2] << 8 | (uint32_t)out[3];
    const bool is_truetype = (magic == 0x00010000u);
    const bool is_cff = (std::memcmp(out.data(), "OTTO", 4) == 0);
    if (!is_truetype && !is_cff) {
        std::fprintf(stderr, "  (magic sfnt obtenu 0x%08x)\n", magic);
        return fail("magic sfnt invalide (ni 0x00010000 ni OTTO)");
    }

    std::printf("woff2_smoketest OK (WOFF2 %zu o -> sfnt %zu o, magic %s)\n",
                in_len, out.size(), is_cff ? "OTTO" : "0x00010000");
    return 0;
}
